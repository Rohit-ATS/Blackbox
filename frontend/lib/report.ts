import type { Answer, RunMetrics } from "./types";

/** A deliberately plain-text handoff: readable in Slack, a ticket, or a terminal. */
export function buildIncidentReport(answer: Answer, metrics?: RunMetrics | null) {
  const lines = [
    `# ${answer.title}`,
    "",
    `- Incident: ${answer.incident_id}`,
    `- Severity: ${answer.severity}`,
  ];

  if (answer.root_cause) {
    const cause = answer.root_cause;
    lines.push("", "## Root cause", `PR #${cause.pr_number} changed ${cause.service}.`);
    if (cause.file) lines.push(`File: ${cause.file}`);
    if (cause.author) lines.push(`Author: ${cause.author}`);
  }

  if (answer.propagation) lines.push("", "## Propagation", answer.propagation.chain.join(" → "));
  if (answer.affected_services) {
    lines.push("", "## Customer impact", `${answer.affected_services.count} services affected.`);
    if (answer.affected_services.customer_facing.length) {
      lines.push(`Customer-facing: ${answer.affected_services.customer_facing.join(", ")}`);
    }
  }
  if (answer.page) lines.push("", "## Page", `${answer.page.name}${answer.page.handle ? ` (@${answer.page.handle})` : ""}`);
  if (answer.memory) {
    lines.push("", "## Memory", `${answer.memory.postmortem_id}${answer.memory.lesson ? `\n${answer.memory.lesson}` : ""}`);
  }
  if (answer.fix) lines.push("", "## Runbook", answer.fix.runbook, answer.fix.body ?? "");
  if (answer.wrote.length) lines.push("", "## Graph write-back", answer.wrote.join(", "));

  if (metrics) {
    lines.push(
      "",
      "## Measured run",
      `- ${metrics.elapsed_ms.toFixed(0)}ms wall clock`
        + ` · ${metrics.tool_calls} tool calls`
        + ` · ${metrics.hops} hops`,
      `- ${metrics.recalled_own_postmortem ? "recalled its own postmortem" : "used seeded history"}`,
    );
  }

  lines.push("", "---", "Generated by BLACKBOX from the cited incident graph.");
  return lines.join("\n").replace(/\n{3,}/g, "\n\n");
}

export function downloadText(filename: string, text: string) {
  const blob = new Blob([text], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = filename;
  anchor.click();
  URL.revokeObjectURL(url);
}
